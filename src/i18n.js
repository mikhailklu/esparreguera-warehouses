const params = new URLSearchParams(location.search);
let lang = params.get('lang') || localStorage.getItem('lang') || (navigator.language?.startsWith('ru') ? 'ru' : 'en');
if (!STR[lang]) lang = 'en';

export const getLang = () => lang;
export function setLang(l) {
  lang = STR[l] ? l : 'en';
  try { localStorage.setItem('lang', lang); } catch { /* ignore */ }
  document.documentElement.lang = lang;
}
export const t = (k) => STR[lang][k] ?? STR.en[k] ?? k;

const locale = () => (lang === 'ru' ? 'ru-RU' : 'en-US');
export const fmt = (n, d = 2) =>
  n.toLocaleString(locale(), { minimumFractionDigits: d, maximumFractionDigits: d });
export const fmtLevel = (v) => `+${v.toFixed(2)}`;
// Signed percentage of a relative difference (e.g. -0.07 → "−7%")
export const fmtPct = (r) => {
  const p = Math.round(r * 100);
  return `${p > 0 ? '+' : p < 0 ? '−' : '±'}${Math.abs(p)}%`;
};
